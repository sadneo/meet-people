import { test,expect } from '@playwright/test'
import { wiringFixture,user } from './wiring-fixture'

for(const width of [390,1280])test(`account earning, purchases and reconciliation ${width}`,async({page},info)=>{
 await page.setViewportSize({width,height:860});const fixture=await wiringFixture(page)
 await page.goto('/home');await expect(page.getByRole('button',{name:'Build with 300 Pebbles'})).toBeVisible()
 const flag=page.getByRole('button',{name:'How to earn Pebbles'})
 await flag.click();const panel=page.getByRole('dialog',{name:'Earn Pebbles'})
 await expect(panel).toBeVisible();await expect(panel.getByRole('heading',{name:'Daily check-in +20',exact:true})).toBeVisible()
 await panel.getByRole('button',{name:'Check in',exact:true}).click();await expect(panel.locator('.garden-collected-quests summary')).toHaveText('Collected (1)')
 await panel.getByRole('button',{name:'Collect',exact:true}).click();await expect(panel.locator('.garden-collected-quests summary')).toHaveText('Collected (2)')
 await page.screenshot({path:info.outputPath('earn-pebbles.png')})
 await page.keyboard.press('Escape');await expect(flag).toBeFocused();await expect(page.getByRole('button',{name:'Build with 420 Pebbles'})).toBeVisible()
 await page.getByRole('button',{name:'Open Garden inventory'}).click();await page.locator('summary[aria-label="Buildings"]').click()
 await page.locator('.garden-shop-item').filter({has:page.getByText('Community Hall',{exact:true})}).getByRole('button',{name:'Build',exact:true}).click()
 await expect(page.getByRole('button',{name:'Build with 300 Pebbles'})).toBeVisible()
 await page.reload();await expect(page.getByRole('button',{name:'Build with 300 Pebbles'})).toBeVisible()
 // A modified browser wallet cannot grant coins or repeat the welcome credit.
 await page.evaluate(id=>{localStorage.setItem(`pebble:full-ui:community:v1:${id}`,JSON.stringify({balance:999999,owned:[],earnedChapters:[]}))},user)
 await page.reload();await expect(page.getByRole('button',{name:'Build with 300 Pebbles'})).toBeVisible()
 await page.getByRole('button',{name:'Open Garden inventory'}).click();await page.locator('summary[aria-label="Random Pebbles"]').click()
 fixture.garden.loseNextResponse()
 await page.locator('.garden-shop-item').filter({has:page.getByText('Random pebble',{exact:true})}).getByRole('button',{name:'Open',exact:true}).click()
 const drawer=page.getByRole('dialog',{name:'Your garden',exact:true})
 await expect(drawer.getByRole('alert')).toBeVisible();await expect(page.locator('.garden-reveal')).not.toBeVisible()
 await drawer.getByRole('button',{name:'Refresh Garden'}).click();await expect(drawer.getByText('0 Pebbles available',{exact:true})).toBeVisible()
 await expect(drawer.getByRole('button',{name:'Place',exact:true})).toHaveCount(1)
 expect(fixture.garden.calls.filter(x=>x.body.action==='geode')).toHaveLength(1)
 await page.getByRole('button',{name:'Close Garden inventory'}).click()
 await page.screenshot({path:info.outputPath('garden-banner.png')})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
test('outage fails closed and can recover; test Pebbles never reach account',async({page})=>{
 const fixture=await wiringFixture(page);fixture.garden.fail(true);await page.goto('/home')
 await expect(page.getByRole('alert')).toContainText('could not be confirmed')
 await page.getByRole('button',{name:'Open Garden inventory'}).click();await page.locator('summary[aria-label="Decorations"]').click()
 await expect(page.locator('.garden-shop-item').filter({has:page.getByText('Garden Bench',{exact:true})}).getByRole('button',{name:'Build',exact:true})).toBeDisabled()
 await page.keyboard.press('Escape');fixture.garden.fail(false);await page.getByRole('button',{name:'Refresh Garden'}).first().click()
 await expect(page.getByRole('button',{name:'Build with 300 Pebbles'})).toBeVisible()
 const menu=page.getByRole('complementary',{name:'Development navigation'});await menu.locator('summary').click()
 await page.getByRole('button',{name:'Add 1,000 test Pebbles'}).click();await expect(page.getByRole('button',{name:'Build with 1300 Pebbles'})).toBeVisible()
 expect(fixture.garden.calls.filter(x=>x.method==='POST')).toHaveLength(0)
 await page.reload();await expect(page.getByRole('button',{name:'Build with 300 Pebbles'})).toBeVisible()
})
