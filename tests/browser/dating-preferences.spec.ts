import { expect, test } from '@playwright/test'
import { sharedProfileFixture } from './shared-profile-fixture'
import { emptyDatingProfile } from '../../shared/dating'

for (const size of [{ width: 320, height: 844 }, { width: 390, height: 844 }, { width: 1440, height: 900 }, { width: 390, height: 420 }]) {
  test(`canonical disabled Dating draft, pending readback and independent search at ${size.width}x${size.height}`, async ({ page }, testInfo) => {
    await page.setViewportSize(size)
    const fixture = await sharedProfileFixture(page)
    let wrote = false, release!: () => void
    const pending = new Promise<void>(done => { release = done })
    await page.route('**/api/matchmaking/dating-preferences', async route => {
      if (route.request().method() === 'PUT') wrote = true
      else if (wrote) await pending
      await route.fallback()
    })
    await page.goto('/matchmaking?view=dating')
    const original = structuredClone(fixture.unified())
    const opener = page.getByRole('button', { name: 'Prototype preferences', exact: true })
    await opener.click()
    const sheet = page.getByRole('dialog', { name: 'Your kind of connection.' })
    await expect(sheet.getByLabel('Show my height on my dating profile')).not.toBeChecked()
    await expect(sheet.getByRole('switch')).toHaveCount(0)
    await sheet.getByLabel('My gender', { exact: true }).selectOption('Other')
    await sheet.getByLabel('My sexuality', { exact: true }).selectOption('Queer')
    await sheet.getByRole('group', { name: 'Dating matching clarification' }).getByRole('checkbox', { name: 'Man', exact: true }).check()
    await sheet.getByLabel('Height in feet').selectOption('5')
    await sheet.getByLabel('Additional height inches').selectOption('0')
    await sheet.getByRole('slider', { name: 'Maximum distance in miles' }).fill('44')
    await sheet.getByRole('radio', { name: 'Temporary search area', exact: true }).check()
    await sheet.getByLabel('Temporary city or campus', { exact: true }).fill('Unresolved synthetic campus')
    await page.screenshot({ path: testInfo.outputPath('dating-canonical-draft.png') })
    await sheet.getByRole('button', { name: 'Save disabled Dating draft' }).click()
    await expect(sheet.getByRole('button', { name: 'Close filters' })).toBeDisabled()
    await page.keyboard.press('Escape'); await expect(sheet).toBeVisible()
    await expect(sheet.getByRole('button', { name: 'Reload saved Dating preferences' })).toBeDisabled()
    await page.screenshot({ path: testInfo.outputPath('dating-pending-readback.png') })
    release()
    await expect(sheet).toHaveCount(0); await expect(opener).toBeFocused()
    await page.reload(); await opener.click()
    await expect(sheet.getByLabel('Additional height inches')).toHaveValue('0')
    await expect(sheet.getByRole('slider', { name: 'Maximum distance in miles' })).toHaveValue('44')
    await expect(sheet.getByText(/No live activation is available/)).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('dating-canonical-reloaded.png') })
    expect(await sheet.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    const bounds = (await sheet.boundingBox())!
    expect(bounds.height).toBeLessThanOrEqual(size.height)
    await page.keyboard.press('Escape')
    await expect(page.getByText('Local prototype recommendations — not live Dating matches.', { exact: true })).toBeVisible()
    await expect(page.locator('[data-front]')).toHaveAttribute('data-dating-card', 'prototype-ari')
    await page.getByRole('link', { name: 'Friends', exact: true }).click()
    await page.getByRole('button', { name: 'Preferences', exact: true }).click()
    await expect(sheet.getByRole('slider', { name: 'Maximum distance in miles' })).toHaveValue('15')
    expect(fixture.unified()).toEqual(original)
    const writes = fixture.calls.filter(call => call.method !== 'GET')
    expect(writes).toHaveLength(1)
    expect(writes[0]).toMatchObject({ path: '/api/matchmaking/dating-preferences', method: 'PUT', body: { expectedProfileRevision: 0, expectedSearchRevision: 0, profile: { heightInches: 60, enabled: false, clarifiedTargets: ['Man'] }, search: { radiusMiles: 44, searchArea: { source: 'temporary', areaLabel: 'Unresolved synthetic campus', resolvedLocationRef: null } } } })
    expect(fixture.external).toEqual([])
  })
}
