import {test,expect} from '@playwright/test'
import {wiringFixture} from './wiring-fixture'
test.use({timezoneId:'Pacific/Honolulu'})
for(const width of [320,390,1280])test(`compact earning menu and server-day tracker ${width}`,async({page},info)=>{
 await page.setViewportSize({width,height:844})
 await page.emulateMedia({reducedMotion:'reduce'})
 const fixture=await wiringFixture(page)
 fixture.garden.rewards({days:['2026-11-02','2026-11-04'],social:{connectionsClaimed:0,connectionAvailable:true,keepInTouchClaimed:false,keepInTouchAvailable:true}})
 await page.goto('/home')
 const flag=page.getByRole('button',{name:'How to earn Pebbles'})
 await expect(page.getByRole('status',{name:'Reward available'})).toBeVisible()
 await page.screenshot({path:info.outputPath('garden-flag.png')})
 await flag.click()
 const panel=page.getByRole('dialog',{name:'Earn Pebbles'})
 await expect(panel.getByRole('listitem')).toHaveCount(7)
 await expect(panel.getByLabel('Monday: checked in',{exact:true})).toBeVisible()
 await expect(panel.getByLabel('Wednesday: checked in',{exact:true})).toBeVisible()
 await expect(panel.getByLabel('Tuesday: not checked in',{exact:true})).toBeVisible()
 await expect(panel.getByLabel('Sunday: not checked in',{exact:true})).toBeVisible()
 await expect(panel.getByText('2 / 5 days',{exact:true})).toBeVisible()
 await page.screenshot({path:info.outputPath('earn-menu.png')})
 const box=await panel.boundingBox();expect(box!.height).toBeLessThan(844*.91)
 expect(await panel.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
 await panel.getByRole('button',{name:'Check in',exact:true}).click()
 await expect(panel.getByLabel('Thursday: checked in',{exact:true})).toBeVisible()
 await panel.getByRole('button',{name:'Collect',exact:true}).click()
 await panel.getByRole('button',{name:'Collect connection reward'}).click()
 await expect(panel.getByText('1 / 2 collected this week')).toBeVisible()
 await panel.getByRole('button',{name:'Collect keep-in-touch reward'}).click()
 await expect(panel.getByRole('button',{name:'Collect keep-in-touch reward'})).not.toBeVisible()
 await expect(panel.locator('.garden-collected-quests summary')).toHaveText('Collected (3)')
 await page.screenshot({path:info.outputPath('collected-collapsed.png')})
 await panel.locator('.garden-collected-quests summary').click()
 await expect(panel.getByRole('button',{name:'Collect keep-in-touch reward'})).toBeDisabled()
 await page.screenshot({path:info.outputPath('collected-expanded.png')})
 await expect(page.getByRole('status',{name:'Reward available'})).toHaveCount(0)
 await page.keyboard.press('Escape');await expect(flag).toBeFocused()
 await expect(page.getByRole('button',{name:'Build with 470 Pebbles'})).toBeVisible()
 await page.reload();await expect(page.getByRole('status',{name:'Reward available'})).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Build with 470 Pebbles'})).toBeVisible()
 expect(fixture.garden.calls.filter(c=>c.body.action==='connection-reward')).toHaveLength(1)
 expect(fixture.garden.calls.filter(c=>c.body.action==='keep-in-touch')).toHaveLength(1)
 // Also review the older response shape shown in the reported spacing screenshot.
 fixture.garden.serverRewards({checkedIn:true,profileClaimed:true,weekDays:2,weekStart:undefined,checkInDays:undefined,social:undefined})
 await flag.click()
 await expect(panel.locator('.garden-check-in-week')).toHaveCount(0)
 await page.screenshot({path:info.outputPath('quest-spacing-without-history.png')})
})
test('claim indicator hides on unavailable state; refresh discovers new server reward',async({page})=>{
 const fixture=await wiringFixture(page);fixture.garden.rewards({collected:true})
 await page.goto('/home');await expect(page.getByRole('button',{name:'Build with 300 Pebbles'})).toBeVisible()
 await expect(page.getByRole('status',{name:'Reward available'})).toHaveCount(0)
 fixture.garden.rewards({social:{connectionsClaimed:1,connectionAvailable:true,keepInTouchClaimed:false,keepInTouchAvailable:false}})
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')))
 await expect(page.getByRole('status',{name:'Reward available'})).toBeVisible()
 fixture.garden.fail(true);await page.evaluate(()=>window.dispatchEvent(new Event('focus')))
 await expect(page.getByRole('alert')).toBeVisible();await expect(page.getByRole('status',{name:'Reward available'})).toHaveCount(0)
})

test('collected quests collapse and recurring quests return on server reset',async({page})=>{
 const fixture=await wiringFixture(page)
 fixture.garden.serverRewards({checkedIn:true,weeklyBonus:true,profileClaimed:true,weekDays:5,social:{connectionsClaimed:2,connectionAvailable:false,keepInTouchClaimed:true,keepInTouchAvailable:false}})
 await page.goto('/home');await page.getByRole('button',{name:'How to earn Pebbles'}).click()
 const panel=page.getByRole('dialog',{name:'Earn Pebbles'}),active=panel.locator('.garden-active-quests'),collected=panel.locator('.garden-collected-quests')
 await expect(active.locator('article')).toHaveCount(0)
 await expect(collected.locator('summary')).toHaveText('Collected (5)')
 await expect(collected).not.toHaveAttribute('open')
 expect(await collected.evaluate(el=>el.nextElementSibling?.classList.contains('garden-reward-rules'))).toBe(true)
 await collected.locator('summary').click();await expect(collected.getByRole('heading')).toHaveCount(5)
 await expect(collected.getByRole('button',{name:'Collected',exact:true})).toHaveCount(2)
 // Device time does not reopen quests. Only a fresh server response does.
 fixture.garden.serverRewards({checkedIn:false,weeklyBonus:true,profileClaimed:true,weekDays:5,day:'2026-11-06',social:{connectionsClaimed:2,connectionAvailable:false,keepInTouchClaimed:true,keepInTouchAvailable:false}})
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')))
 await expect(active.getByRole('button',{name:'Check in',exact:true})).toBeEnabled()
 await expect(collected.locator('summary')).toHaveText('Collected (4)')
 fixture.garden.serverRewards({checkedIn:false,weeklyBonus:false,profileClaimed:true,weekDays:0,day:'2026-11-09',weekStart:'2026-11-09',checkInDays:[],social:{connectionsClaimed:0,connectionAvailable:false,keepInTouchClaimed:false,keepInTouchAvailable:false}})
 await page.evaluate(()=>window.dispatchEvent(new Event('focus')))
 await expect(active.locator('article')).toHaveCount(4)
 await expect(active.getByRole('heading',{name:'Come back five days +50'})).toBeVisible()
 await expect(active.getByRole('heading',{name:'Build a connection +30'})).toBeVisible()
 await expect(active.getByRole('heading',{name:'Keep in touch +20'})).toBeVisible()
 await expect(collected.locator('summary')).toHaveText('Collected (1)')
 await expect(collected.getByRole('heading',{name:'Complete onboarding +100'})).toBeVisible()
 for(const copy of ['A little hello','A one-time welcome','Both chat on two days','Reconnect on two days','Day-by-day history','Available after the rewards update'])await expect(active).not.toContainText(copy)
})
