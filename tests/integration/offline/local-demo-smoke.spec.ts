import { test,expect } from '@playwright/test'
test('real local development sign-in and authenticated capability readback',async({page})=>{
 test.setTimeout(60000)
 await page.route('**/*',route=>{const u=new URL(route.request().url());if(!['127.0.0.1','localhost'].includes(u.hostname)){return route.abort()}return route.continue()})
 // No SDK interception, credentials, session output, traces or provider data logs.
 await page.goto('/login')
 const development=page.getByRole('button',{name:'Sign in as development user',exact:true})
 await expect(development).toBeVisible();await expect(development).toBeEnabled()
 await development.click()
 await expect(page).not.toHaveURL(/\/login/,{timeout:20000})
 await page.goto('/matchmaking?view=dating')
 await expect(page.getByRole('button',{name:'Dating preferences',exact:true})).toBeVisible()
 await expect(page.getByText('Local prototype recommendations — not live Dating matches.',{exact:true})).toHaveCount(0)
 await expect(page.getByRole('button',{name:/^(Start|Pause) Dating discovery$/})).toBeVisible()
 await page.getByRole('button',{name:'Dating preferences',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'Your kind of connection.',exact:true})).toBeVisible()
 await page.keyboard.press('Escape')
 await page.goto('/profile')
 await page.getByRole('button',{name:'Profile picture',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Your profile picture',exact:true})
 await expect(dialog.getByLabel('Choose a picture')).toBeEnabled()
 await dialog.getByRole('button',{name:'Cancel',exact:true}).click()
 console.log('PASS actual local Auth + API/PostgREST: real Dating capability, preferences, own photo state. No search, upload or account changes performed.')
})
