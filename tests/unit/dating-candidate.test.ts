// @vitest-environment node
import { readFileSync } from 'node:fs'
import { expect, it } from 'vitest'

const sql = readFileSync(new URL('../../docs/dating-aggregate-migration.sql', import.meta.url), 'utf8')
const acceptance = readFileSync(new URL('../integration/sql/dating-aggregate.sql', import.meta.url), 'utf8')
it('keeps the candidate additive/private, actor-derived and independent of all operational/legacy writers (source checks only)', () => {
  expect(sql).toContain('actor uuid:=auth.uid()')
  expect(sql).toContain("set search_path=''")
  expect(sql).toContain('alter table public.dating_owner_aggregates enable row level security')
  expect(sql).toContain('revoke all on public.dating_owner_aggregates from public, anon, authenticated')
  expect(sql).not.toMatch(/create or replace|drop\s|update public\.profiles|insert into public\.(profiles|queue_entries|friends_search_preferences|dating_matches)/i)
  expect(sql).toContain("current_setting('transaction_isolation')<>'read committed'")
  expect(sql).toContain('previous.profile_revision,0)<>ep or coalesce(previous.search_revision,0)<>es')
  expect(sql).toContain('profile_revision=profile_revision+1,search_revision=search_revision+1,profile=p,search=s')
  expect(sql).toContain("using errcode='DA409'")
  expect(sql).toContain('Identity edit must clear clarification')
  expect(sql.match(/as_of date:=public\.dating_campus_date\(transaction_timestamp\(\)\)/g)).toHaveLength(2)
  expect(sql).toContain("(instant_in at time zone 'America/New_York')::date")
  expect(sql).not.toContain("at time zone 'UTC'")
  expect(sql).toContain('not between 24 and 107')
  expect(sql).toContain('if previous.user_id is not null')
  expect(sql).toContain("(previous.profile->>'gender' collate \"C\")<>'' or (previous.profile->>'sexuality' collate \"C\")<>''")
  expect(sql).toContain('public.dating_adult_on(dob,as_of)')
  expect(sql).toContain('public.dating_location_resolved(actor,s,home)')
})
it('provides guarded rollback acceptance source, not SQL installation/runtime/concurrency evidence', () => {
  expect(acceptance).toContain("current_database()<>'pebble_dating_disposable'")
  expect(acceptance).toContain("current_setting('pebble.dating_test_target',true)")
  expect(acceptance).toContain('pg_get_userbyid(relowner)')
  expect(acceptance).toContain('has_any_column_privilege')
  expect(acceptance).toContain('set local role authenticated')
  expect(acceptance).toContain('Stale search accepted'); expect(acceptance).toContain('Stale profile accepted')
  expect(acceptance).toContain('Failed aggregate partially changed a resource')
  expect(acceptance).toContain('Foreign ref accepted')
  expect(acceptance).toContain('Revoked ref failed to mask stored consent')
  expect(acceptance).toContain('2026-01-15 04:59:59+00')
  expect(acceptance).toContain('2026-07-15 03:59:59+00')
  expect(acceptance).toContain('First clarification from empty draft rejected')
  expect(acceptance).toContain('Partial identity reused clarification')
  expect(acceptance.trim()).toMatch(/rollback;$/)
})
