// @vitest-environment node
import { readFileSync } from 'node:fs'
import { expect, it } from 'vitest'

// Verification commands run from the approved repository root. Do not derive
// filesystem paths from Vite's runner/browser-origin import.meta.url.
const sql = readFileSync('supabase/schema-sources/safety-owner-contact-migration.sql', 'utf8')
const acceptance = readFileSync('tests/integration/sql/safety-owner-contact.sql', 'utf8')
const races = readFileSync('tests/integration/sql/safety-owner-race-session.sql', 'utf8')
it('uses canonical blocks and one ordered pair key on block and legacy contact guards (static source, not runtime evidence)', () => {
  expect(sql).toContain("least(a,b)::text||':'||greatest(a,b)::text")
  expect(sql).toContain('pg_catalog.pg_advisory_xact_lock')
  expect(sql).not.toMatch(/lock\s+table|drop\s+.*cascade|delete from public\.(messages|conversations|connections)/i)
  expect(sql).toContain('before insert or update or delete on public.blocks')
  expect(sql).toContain('before insert or update or delete on public.connections')
  expect(sql).toContain('before insert or update on public.conversations')
  expect(sql).toContain('before insert or update on public.messages')
  expect(sql).toContain('before insert or update on public.dating_matches')
  expect(sql).toContain("current_setting('transaction_isolation')<>'read committed'")
  expect(sql).toContain('safety_private.revoked_connections')
  expect(sql).toContain('new.body,new.created_at')
  expect(sql).toContain('Inherited browser bypass requires review')
  expect(sql).toContain("has_sequence_privilege(r::name,seq,'SELECT,USAGE,UPDATE')")
  expect(sql).toContain('Inherited sequence bypass requires review')
  expect(sql).toContain('old.sender_id is null')
  expect(sql).toContain('old.sender_id<>a and old.sender_id<>b')
  expect(sql).toContain("to_regprocedure('auth.uid()') is null")
  expect(sql).toContain('Scalar UUID auth.uid prerequisite required')
  const maintenance = sql.slice(sql.indexOf('create function safety_private.maintenance()'), sql.indexOf('create table safety_private.revoked_connections'))
  expect(maintenance).toContain('from pg_catalog.pg_roles')
  expect(maintenance).not.toMatch(/\bfrom\s+pg_roles\b/)
  expect(sql).toContain('get_my_conversations()'); expect(sql).toContain('mark_conversation_read(bigint)')
})
it('does not query hidden profile metadata for blocklists or claim all-surface authority; report rate/idempotency remains owner scoped', () => {
  const getter = sql.slice(sql.indexOf('create or replace function public.get_owner_blocklist()'), sql.indexOf('create function public.block_owner_target'))
  expect(getter).not.toContain('public.profiles'); expect(getter).toContain("'displayName',null")
  expect(getter).toContain('contact-mutations-only')
  expect(sql).toContain('primary key(actor_id,request_id)')
  expect(sql).toContain("errcode='SR409'"); expect(sql).toContain("errcode='SR429'")
  expect(sql).toContain("interval '1 hour')>=5")
  expect(sql).toContain("interval '24 hours')>=20")
})
it('guards parent SQL/observed-wait sources and preserves exact historical scalar compatibility', () => {
  expect(acceptance).toContain("current_database()<>'pebble_safety_owner_disposable'")
  expect(acceptance).toContain('pg_get_userbyid(relowner)')
  expect(acceptance).toContain('has_any_column_privilege')
  expect(acceptance).toContain("prorettype='pg_catalog.int4'::regtype")
  expect(acceptance).toContain('Reverse-blocked send accepted')
  expect(acceptance).toContain('Unblock resurrected old relationship')
  expect(acceptance).toContain('safety_owner_inherited_sequence_fixture')
  expect(acceptance).toContain('Rejected install was not atomic')
  expect(acceptance).toContain('Synthetic malformed NULL sender history')
  expect(acceptance).toContain('Malformed pre-install history changed')
  expect(acceptance).toContain('Reverse-blocked recipient receipt accepted')
  expect(acceptance.trim()).toMatch(/rollback;$/)
  expect(races).toContain('pg_blocking_pids(loser.pid)')
  expect(races).toContain("loser.wait_event_type='Lock'")
  expect(races).toContain('legacy_block')
  expect(races).toContain('commit_resolution'); expect(races).toContain('rollback_resolution')
  expect(races).not.toContain('pg_sleep')
  expect(races).toContain('legacy_unblock')
  expect(races).toContain('profile_delete')
  expect(races).toContain('hold_row_mode')
  expect(races).toContain('40P01')
  expect(races).toContain('42501')
})
