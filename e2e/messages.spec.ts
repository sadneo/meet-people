import { expect, test } from '@playwright/test'

test('desktop reference has three panes and searchable, selectable conversations', async ({ page }) => {
  await page.setViewportSize({ width: 1672, height: 941 })
  await page.goto('/messages')
  await expect(page.locator('.pt-inbox-pane')).toBeVisible()
  await expect(page.locator('.pt-conversation-pane')).toBeVisible()
  await expect(page.locator('.pt-chat-details')).toBeVisible()
  await expect(page.locator('.pt-conversation')).toHaveCount(5)
  await expect(page.locator('.pt-conversation.is-selected')).toContainText('Jamie Chen')
  await expect(page.locator('.pt-conversation').first().getByLabel('Unread conversation')).toHaveCount(0)
  await expect(page.getByLabel('Unread conversation')).toHaveCount(1)
  await expect(page.locator('.pt-message-row')).toHaveCount(5)
  await expect(page.locator('.pt-chat-details')).toContainText('Brew House Café')
  await expect(page.locator('.pt-chat-details')).toContainText('Fall Social Mixer')
  expect(await page.locator('.pt-chat-details img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true)

  await page.getByRole('searchbox', { name: 'Search conversations' }).fill('Alex')
  await expect(page.locator('.pt-conversation')).toHaveCount(1)
  await page.locator('.pt-conversation').click()
  await expect(page).toHaveURL('/messages/chat')
  await expect(page.locator('.pt-chat-identity')).toContainText('Alex Park')
  await expect(page.locator('.pt-chat-details h2').first()).toHaveText('Alex Park')
  await expect(page.getByLabel('Unread conversation')).toHaveCount(0)
  await page.getByLabel('Message', { exact: true }).fill('Want to get coffee tomorrow?')
  await page.getByRole('button', { name: 'Add an emoji' }).click()
  await page.getByRole('button', { name: 'Insert ☕' }).click()
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('.pt-chat-bubble').last()).toHaveText('Want to get coffee tomorrow?☕')
  await expect(page.getByLabel('Message', { exact: true })).toHaveValue('')

  await page.getByRole('link', { name: 'Events', exact: true }).click()
  await page.getByRole('link', { name: 'Messages', exact: true }).click()
  await expect(page.locator('.pt-conversation.is-selected')).toContainText('Alex Park')
  await expect(page.locator('.pt-chat-identity')).toContainText('Alex Park')

  await page.getByRole('searchbox', { name: 'Search conversations' }).fill('Jamie')
  await page.locator('.pt-conversation').click()
  await expect(page.locator('.pt-chat-identity')).toContainText('Jamie Chen')
  await expect(page.getByText('Want to get coffee tomorrow?☕', { exact: true })).toHaveCount(0)
  await page.getByRole('searchbox', { name: 'Search conversations' }).fill('nobody')
  await expect(page.getByText('No conversations found. Try another name.')).toBeVisible()

  await page.getByRole('button', { name: 'Voice call' }).click()
  await expect(page.getByRole('dialog')).toContainText('Calls are not connected in this demo.')
  await page.getByRole('button', { name: 'Close dialog' }).click()
  await page.getByRole('button', { name: 'Make a plan', exact: true }).click()
  await expect(page).toHaveURL('/free-time/plan')
  await expect(page.getByRole('heading', { name: 'Choose your shared time' })).toBeVisible()
})

test('compact chat keeps sending and demo attachments usable', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/messages')
  await expect(page.locator('.pt-chat-details')).toBeHidden()
  await expect(page.locator('.pt-conversation.is-selected')).toHaveCount(0)
  await expect(page.getByLabel('Unread conversation')).toHaveCount(2)
  await page.locator('.pt-conversation').first().click()
  await expect(page.locator('.pt-inbox-pane')).toBeHidden()
  await page.locator('input[type=file]').setInputFiles({ name: 'coffee-plan.txt', mimeType: 'text/plain', buffer: Buffer.from('Meet by the window') })
  await expect(page.getByLabel('Message', { exact: true })).toHaveValue('[Demo attachment: coffee-plan.txt]')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('.pt-chat-bubble').last()).toHaveText('[Demo attachment: coffee-plan.txt]')
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page).toHaveURL('/messages')
  await expect(page.locator('.pt-conversation.is-selected')).toHaveCount(0)
  await expect(page.getByLabel('Unread conversation')).toHaveCount(1)
  await expect(page.locator('.pt-conversation').first()).toContainText('coffee-plan.txt')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('selection and read receipts follow the 800px layout boundary', async ({ page }) => {
  await page.setViewportSize({ width: 799, height: 844 })
  await page.goto('/messages')
  await expect(page.locator('.pt-conversation.is-selected')).toHaveCount(0)
  await expect(page.getByLabel('Unread conversation')).toHaveCount(2)

  await page.setViewportSize({ width: 800, height: 844 })
  await expect(page.locator('.pt-conversation.is-selected')).toHaveCount(0)
  await expect(page.getByLabel('Unread conversation')).toHaveCount(2)

  await page.setViewportSize({ width: 801, height: 844 })
  await expect(page.locator('.pt-conversation.is-selected')).toContainText('Jamie Chen')
  await expect(page.getByLabel('Unread conversation')).toHaveCount(1)

  await page.setViewportSize({ width: 800, height: 844 })
  await expect(page.locator('.pt-conversation.is-selected')).toHaveCount(0)
  await expect(page.getByLabel('Unread conversation')).toHaveCount(1)
})

test('opening a compact chat directly marks its messages read', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/messages/chat')
  await expect(page.locator('.pt-chat-identity')).toContainText('Jamie Chen')
  await page.getByRole('button', { name: 'Back', exact: true }).click()
  await expect(page.locator('.pt-conversation.is-selected')).toHaveCount(0)
  await expect(page.locator('.pt-conversation').first().getByLabel('Unread conversation')).toHaveCount(0)
  await expect(page.getByLabel('Unread conversation')).toHaveCount(1)
})
