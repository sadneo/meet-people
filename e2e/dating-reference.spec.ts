import { expect, test } from '@playwright/test'
import { sharedProfileFixture } from './shared-profile-fixture'

for (const size of [{width:320,height:740},{width:375,height:812},{width:390,height:844},{width:430,height:932},{width:505,height:664},{width:800,height:1100},{width:1440,height:900},{width:390,height:480}]) {
  test(`Dating card metadata and preferences reference ${size.width}x${size.height}`, async ({ page }, testInfo) => {
    await page.setViewportSize(size)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.route('**/*', route => new URL(route.request().url()).origin === 'http://127.0.0.1:3194' ? route.continue() : route.abort())
    const fixture = await sharedProfileFixture(page)
    const apiRequests: string[] = []
    page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/')) apiRequests.push(`${request.method()} ${new URL(request.url()).pathname}`) })
    await page.goto('/matchmaking?view=dating')
    const front = page.locator('[data-front]')
    await expect(front.getByRole('heading', { name: 'Ari, 24', exact: true })).toBeVisible()
    await expect(page.getByText('Local prototype recommendations — not live Dating matches.', { exact: true })).toBeVisible()
    await expect(front.locator('img')).toHaveAttribute('src', '/prototype/dating/ari.jpg')
    await expect.poll(() => front.locator('img').evaluate(element => (element as HTMLImageElement).complete && (element as HTMLImageElement).naturalWidth > 0)).toBe(true)
    await front.locator('img').evaluate(async element => { await (element as HTMLImageElement).decode(); await new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))) })
    await expect(front.getByRole('list', { name: 'Prototype interests' }).getByRole('listitem')).toHaveCount(3)
    await expect(front.getByRole('definition')).toHaveText(['North campus', '3 miles', '5′7″'])
    await expect(front.locator('.dating-bio')).toHaveCount(0)
    await expect(page.locator('.dating-pagination')).toHaveCount(0)
    await expect(page.getByText(/Art walks, coffee stops, and taking/)).toHaveCount(0)
    for (const item of await front.locator('.dating-card-info dd').all()) {
      const bounds = (await item.boundingBox())!, card = (await front.boundingBox())!
      expect(bounds.x).toBeGreaterThanOrEqual(card.x)
      expect(bounds.x + bounds.width).toBeLessThanOrEqual(card.x + card.width)
      const actions = (await page.locator('.dating-decisions').boundingBox())!
      expect(bounds.y + bounds.height <= actions.y || bounds.x + bounds.width <= actions.x || bounds.x >= actions.x + actions.width).toBe(true)
    }
    await page.screenshot({ path: testInfo.outputPath('card.png') })
    const opener = page.getByRole('button', { name: 'Prototype preferences', exact: true })
    await opener.click()
    const sheet = page.getByRole('dialog', { name: 'Your kind of connection.', exact: true })
    await expect(sheet).toHaveCSS('background-color', 'rgb(250, 248, 240)')
    await expect(sheet).toHaveCSS('border-top-left-radius', '26px')
    await expect(sheet.getByText('Dating preferences', { exact: true })).toBeVisible()
    await expect(sheet.getByRole('slider')).toHaveCount(3)
    await expect(sheet.getByRole('spinbutton')).toHaveCount(0)
    if (size.width <= 800) await expect(sheet.locator('.mfs-grabber')).toBeVisible(); else await expect(sheet.locator('.mfs-grabber')).toBeHidden()
    const gender = sheet.getByLabel('My gender', { exact: true })
    await expect(sheet.getByRole('combobox')).toHaveCount(6)
    await expect(page.getByRole('dialog')).toHaveCount(1)
    const bounds = (await sheet.boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.y).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(size.width)
    expect(bounds.y + bounds.height).toBeLessThanOrEqual(size.height)
    expect(await sheet.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath('preferences.png') })
    const distance = sheet.getByRole('slider', { name: 'Maximum distance in miles' })
    await distance.focus(); await page.keyboard.press('End')
    await expect(distance).toHaveValue('100')
    await gender.selectOption('Other')
    await sheet.getByLabel('Height in feet').selectOption('6')
    await sheet.getByLabel('Additional height inches').selectOption('0')
    await sheet.getByRole('button', { name: 'Reset', exact: true }).click()
    await expect(gender).toHaveValue('Other')
    await distance.focus(); await page.keyboard.press('End')
    await sheet.screenshot({ path: testInfo.outputPath('full-preferences.png') })
    await sheet.getByRole('button', { name: 'Save disabled Dating draft', exact: true }).click()
    await expect(sheet).toHaveCount(0); await expect(opener).toBeFocused()
    await opener.click(); await expect(sheet.getByRole('slider', { name: 'Maximum distance in miles' })).toHaveValue('100')
    await expect(gender).toHaveValue('Other')
    await page.keyboard.press('Escape')
    await expect(front.getByRole('definition')).toHaveText(['North campus', '3 miles', '5′7″'])
    await page.reload(); await opener.click()
    await expect(sheet.getByRole('slider', { name: 'Maximum distance in miles' })).toHaveValue('100')
    await expect(gender).toHaveValue('Other')
    await page.keyboard.press('Escape')
    expect(apiRequests.filter(request => !request.startsWith('GET '))).toEqual(['PUT /api/matchmaking/dating-preferences'])
    expect(fixture.calls.filter(call => call.method === 'PUT')[0].body).toMatchObject({ profile: { heightInches: 72, enabled: false }, search: { radiusMiles: 100 } })
    expect(fixture.external).toEqual([])
    expect(await page.evaluate(() => localStorage.getItem('pebble.match-filters.v1'))).toBeNull()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(size.width)
  })
}

test('mobile pull-down threshold discards drafts; short and cancelled pulls keep the sheet', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.route('**/*', route => new URL(route.request().url()).origin === 'http://127.0.0.1:3194' ? route.continue() : route.abort())
  const fixture = await sharedProfileFixture(page)
  await page.goto('/matchmaking?view=dating')
  const opener = page.getByRole('button', { name: 'Prototype preferences', exact: true })
  await opener.click()
  const sheet = page.getByRole('dialog', { name: 'Your kind of connection.' })
  const pull = async (distance: number) => {
    await sheet.evaluate(element => { element.scrollTop = 0 })
    await expect(sheet).toHaveCSS('transform', 'none')
    const box = (await sheet.locator('.mfs-header h2').boundingBox())!
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down(); await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + distance, { steps: 8 }); await expect(sheet).toHaveAttribute('data-dragging', 'true'); await page.mouse.up()
  }
  await sheet.getByLabel('My gender', { exact: true }).selectOption('Other')
  await pull(60); await expect(sheet).toBeVisible()
  await expect(sheet.getByLabel('My gender', { exact: true })).toHaveValue('Other')
  await pull(120); await expect(sheet).toHaveCount(0); await expect(opener).toBeFocused()
  await opener.click(); await expect(sheet.getByLabel('My gender', { exact: true })).toHaveValue('')
  const region = (await sheet.locator('.mfs-grabber').boundingBox())!
  await page.mouse.move(region.x, region.y); await page.mouse.down()
  await sheet.locator('.mfs-drag-region').dispatchEvent('pointercancel', { pointerId: 1 }); await page.mouse.up()
  await expect(sheet).toBeVisible()
  expect(fixture.calls.every(call => call.method === 'GET')).toBe(true)
  expect(fixture.external).toEqual([])
})
