import { expect, test } from '@playwright/test'
import { COMMUNITY_STORAGE_KEY } from '../src/features/prototype/economy'

for (const [width, height] of [[320, 568], [390, 844], [1280, 720]]) {
  test(`Rare Finds and confirmed purchase refunds at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height })
    await page.addInitScript(key => {
      if (!localStorage.getItem(key)) localStorage.setItem(key, JSON.stringify({ balance: 2000, owned: [], earnedChapters: [0], positions: { pebble: { x: 744, y: 660 } } }))
    }, COMMUNITY_STORAGE_KEY)
    await page.goto('/community')
    const bars = page.getByRole('group', { name: 'Select a day' }).getByRole('button')
    await bars.first().click()
    const sundayBase = await page.locator('[data-village-base]').getAttribute('href')
    const sundayImage = await page.locator('.pt-community-world').screenshot()
    await bars.last().click()
    await page.getByRole('button', { name: 'Build your community', exact: true }).click()
    const shop = page.getByRole('dialog', { name: 'Build your community', exact: true })
    await expect(shop.getByRole('heading', { name: 'Rare Finds' })).toBeInViewport()
    await expect(shop.getByRole('button', { name: 'Reset purchases', exact: true })).toBeEnabled()
    const panel = (await shop.boundingBox())!
    expect(panel.width).toBeLessThanOrEqual(width > 800 ? 360 : 340)
    expect(panel.width).toBeLessThan(width)
    await expect(shop.locator('article p, article small')).toHaveCount(0)
    if (width > 800) {
      const world = (await page.locator('.pt-community-world').boundingBox())!
      expect(panel.x - world.x).toBeGreaterThan(world.width * .6)
    }
    const rare = shop.getByRole('region', { name: 'Rare Finds' })
    await expect(rare.getByRole('article')).toHaveCount(4)
    await page.screenshot({ path: `/tmp/pebble-build-${width}-rare-top.png` })
    for (const name of ['Garnet', 'Sapphire', 'Emerald', 'Citrine']) {
      const article = rare.getByRole('article', { name, exact: true })
      await article.scrollIntoViewIfNeeded()
      await expect(article).toBeInViewport()
      await expect(article).toContainText('300 Pebbles')
      await expect(article.locator('image')).toHaveAttribute('href', /expressive-pebbles/)
      await article.getByRole('button', { name: `Build ${name}`, exact: true }).click()
      await expect(article.getByRole('button', { name: `Owned ${name}` })).toBeDisabled()
    }
    await shop.getByRole('button', { name: 'Build Garden Bench', exact: true }).click()
    await expect(shop).toContainText('785 Pebbles available')
    await page.keyboard.press('Escape')
    for (const id of ['garnet', 'sapphire', 'emerald', 'citrine']) {
      const item = page.locator(`[data-upgrade="${id}"]`)
      await expect(item).toHaveAttribute('data-movable', 'true')
      const before = await item.getAttribute('transform'), box = (await item.locator(':scope > rect').boundingBox())!
      const x = box.x + box.width / 2, y = box.y + box.height / 2
      await page.mouse.move(x, y)
      await page.mouse.down()
      await page.mouse.move(x + 16, y - 10, { steps: 8 })
      await page.mouse.up()
      await expect(item).not.toHaveAttribute('transform', before!)
    }
    await page.reload()
    await page.getByRole('button', { name: 'Build your community', exact: true }).click()
    await shop.getByRole('button', { name: 'Reset purchases', exact: true }).click()
    const confirm = page.getByRole('alertdialog')
    await expect(confirm).toHaveAccessibleName('Reset your entire Pebble Community?')
    await expect(confirm).toContainText('This removes all purchased items and restores your spent Pebbles. 1215 Pebbles will be returned.')
    await expect(confirm.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
    await page.screenshot({ path: `/tmp/pebble-build-${width}-confirm.png` })
    await confirm.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(confirm).toBeHidden()
    await expect(shop).toContainText('785 Pebbles available')
    await expect(page.locator('[data-upgrade]')).toHaveCount(5)
    await shop.getByRole('button', { name: 'Reset purchases', exact: true }).click()
    await page.keyboard.press('Escape')
    await expect(confirm).toBeHidden()
    await expect(shop).toBeVisible()
    await shop.getByRole('button', { name: 'Reset purchases', exact: true }).click()
    await confirm.getByRole('button', { name: 'Reset everything', exact: true }).click()
    await expect(shop).toBeHidden()
    await expect(page.getByLabel('Pebble balance', { exact: true })).toContainText('2000')
    await expect(page.locator('[data-upgrade]')).toHaveCount(0)
    await expect(page.locator('[data-village-base]')).toHaveAttribute('href', sundayBase!)
    await expect(page.locator('[data-object]')).toHaveCount(1)
    await expect(page.locator('[data-terrain]')).toHaveCount(0)
    await expect(page.locator('[data-object="pebble"]')).toHaveAttribute('transform', 'translate(724 595)')
    expect(await page.locator('.pt-community-world').screenshot()).toEqual(sundayImage)
    await page.screenshot({ path: `/tmp/pebble-build-${width}-reset-base.png` })
    const saved = await page.evaluate(key => JSON.parse(localStorage.getItem(key)!), COMMUNITY_STORAGE_KEY)
    expect(saved.positions).toEqual({})
    expect(saved.freshStart).toBe(true)
    expect(saved.earnedChapters).toEqual([0])
    expect(saved.purchaseCosts).toEqual({})
    await page.reload()
    await expect(page.locator('[data-object]')).toHaveCount(1)
    await page.getByRole('button', { name: 'Build your community', exact: true }).click()
    await expect(shop.getByRole('button', { name: 'Reset purchases', exact: true })).toBeDisabled()
    for (const name of ['Garnet', 'Sapphire', 'Emerald', 'Citrine', 'Garden Bench']) await expect(shop.getByRole('button', { name: `Build ${name}`, exact: true })).toBeEnabled()
    await expect(shop).toContainText('2000 Pebbles available')
    await shop.getByRole('button', { name: 'Build Garnet', exact: true }).click()
    await expect(shop).toContainText('1700 Pebbles available')
    await page.keyboard.press('Escape')
    await expect(page.locator('[data-object]')).toHaveCount(2)
    await expect(page.locator('[data-village-base]')).toHaveAttribute('href', sundayBase!)
    await expect(page.locator('[data-upgrade="garnet"]')).toHaveAttribute('data-movable', 'true')
  })
}
