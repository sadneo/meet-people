import { expect, test } from '@playwright/test'
import { sharedProfileFixture } from './shared-profile-fixture'
import { chooseDistanceAndGroup, saveInterestChapter, saveSocialChapter } from './onboarding-fixture'

for (const width of [320, 1440]) {
  test(`first-time Profile ${width}: explicit identity, initial preferences, readback and bidirectional route/reload`, async ({ page }) => {
    const fixture = await sharedProfileFixture(page, { identity: 'missing', missingProfile: true })
    await page.setViewportSize({ width, height: width === 320 ? 568 : 900 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await page.goto('/profile')
    await expect(page.getByRole('heading', { name: 'Complete onboarding', exact: true })).toBeVisible()
    const completion = page.locator('.pt-access-card')
    const editor = page.getByRole('dialog', { name: 'Edit your profile', exact: true })
    await expect(completion.getByLabel('Username', { exact: true })).toHaveValue('')
    await expect(completion.getByLabel('Display name', { exact: true })).toHaveValue('')
    await expect(completion.getByRole('button', { name: 'Save identity and continue', exact: true })).toBeDisabled()
    await expect(completion.getByRole('button', { name: 'Save shared preferences', exact: true })).toHaveCount(0)
    expect(fixture.calls.every(call => call.method === 'GET')).toBe(true)
    await completion.getByLabel('Username', { exact: true }).fill('explicit-fixture')
    await completion.getByLabel('Display name', { exact: true }).fill('Explicit fixture')
    await completion.getByLabel('Bio', { exact: true }).fill('User-entered fixture bio')
    const sizes = await completion.locator('input, textarea, button').evaluateAll(elements => elements.map(element => element.getBoundingClientRect()).filter(box => box.width && box.height).map(box => ({ width: box.width, height: box.height })))
    for (const box of sizes) { expect(box.width).toBeGreaterThanOrEqual(44); expect(box.height).toBeGreaterThanOrEqual(44) }
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    await page.screenshot({ path: `worktree/profile-creation/identity-${width}.png`, animations: 'disabled' })
    await completion.getByRole('button', { name: 'Save identity and continue', exact: true }).click()
    await expect(page.locator('.pt-app')).toHaveCount(0)
    await saveInterestChapter(page); await saveSocialChapter(page)
    const save = completion.getByRole('button', { name: 'Finish onboarding', exact: true })
    await expect(save).toBeEnabled()
    expect(fixture.account()).toEqual({ username: 'explicit-fixture', display_name: 'Explicit fixture', bio: 'User-entered fixture bio', avatar_url: null })
    expect(fixture.profile()).toMatchObject({ interests: ['Music', 'Coffee', 'Art'], availability: [], birthdate: null, location_city: null })
    await expect(completion.getByLabel('Username', { exact: true })).toHaveCount(0)
    await chooseDistanceAndGroup(page)
    await completion.getByRole('button', { name: 'Sunday late, not available', exact: true }).click()
    await completion.getByLabel('City or campus area').fill('User-entered campus')
    await completion.getByLabel('Birthdate', { exact: true }).fill('2001-02-03')
    await completion.getByRole('group', { name: 'Interests', exact: true }).evaluate(element => element.scrollIntoView({ block: 'start' }))
    await page.screenshot({ path: `worktree/profile-creation/preferences-${width}.png`, animations: 'disabled' })
    await save.scrollIntoViewIfNeeded(); await expect(save).toBeInViewport(); await save.click()
    await expect(page).toHaveURL('/profile')
    await expect(editor).toHaveCount(0)
    expect(fixture.profile()).toMatchObject({ ...fixture.account(), interests: ['Music', 'Coffee', 'Art'], location_city: 'User-entered campus', birthdate: '2001-02-03', availability: [{ dow: 0, start_time: '21:00:00', end_time: '24:00:00' }] })
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Explicit fixture', exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Matchmaking', exact: true }).first().click()
    await page.getByRole('button', { name: 'Preferences', exact: true }).click()
    const matching = page.getByRole('dialog', { name: 'Your preferences', exact: true })
    await expect(matching.getByRole('button', { name: 'Music', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(matching.getByLabel('City or campus area')).toHaveCount(0)
    await matching.getByRole('button', { name: 'Sports', exact: true }).click()
    await matching.getByRole('button', { name: 'Save preferences', exact: true }).click()
    await expect(matching).toHaveCount(0)
    if (width > 800) await page.getByRole('button', { name: 'Account menu', exact: true }).click()
    await page.getByRole('link', { name: 'Profile', exact: true }).first().click()
    await page.reload()
    await page.getByRole('button', { name: 'Edit profile', exact: true }).click()
    await expect(editor.getByRole('button', { name: 'Sports', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(editor.getByRole('button', { name: 'Music', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(editor.getByLabel('City or campus area')).toHaveValue('User-entered campus')
    expect(fixture.calls.filter(call => call.method === 'PUT').map(call => call.path)).toEqual([...Array(4).fill('/api/matchmaking/account'), '/api/matchmaking/profile'])
    expect(fixture.calls.some(call => /\/(queue|result)$/.test(call.path))).toBe(false)
    expect(fixture.external).toEqual([])
  })
}

for (const width of [320, 1440]) test(`uninstalled identity support ${width} stays unavailable, not an editable first-time identity`, async ({ page }) => {
  const fixture = await sharedProfileFixture(page, { identity: 'unavailable', missingProfile: true })
  await page.setViewportSize({ width, height: width === 320 ? 568 : 900 })
  await page.goto('/profile')
  await expect(page.getByRole('heading', { name: 'Profile unavailable', exact: true })).toBeVisible()
  await expect(page.locator('.pt-app')).toHaveCount(0)
  await expect(page.getByLabel('Username', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('alert')).toContainText('Your saved account could not be read')
  await page.screenshot({ path: `worktree/profile-readiness/unavailable-${width}.png`, animations: 'disabled' })
  await page.getByRole('button', { name: 'Retry account', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Your saved account could not be read')
  expect(fixture.calls.every(call => call.method === 'GET' && call.path === '/api/matchmaking/account')).toBe(true)
  expect(fixture.external).toEqual([])
})
