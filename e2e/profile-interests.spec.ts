import { expect, test } from '@playwright/test'
import { sharedProfileFixture } from './shared-profile-fixture'

for (const [width, height] of [[320, 568], [320, 400], [390, 844], [801, 900], [1440, 900]]) test(`inline usual preferences ${width}x${height}: 30 labels, exact cells, staged cancellation and overflow`, async ({ page }) => {
  const fixture = await sharedProfileFixture(page, { interests: Array.from({ length: 30 }, (_, index) => `Label ${index + 1}`) })
  await page.setViewportSize({ width, height })
  await page.goto('/profile')
  const interests = page.getByRole('group', { name: 'Usual interests' })
  await expect(interests.getByRole('button', { name: 'Label 30', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '+ Add an interest', exact: true }).click()
  await page.getByLabel('Your own interest').fill('Unsent label')
  await page.getByRole('button', { name: 'Add interest', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('30 interests')
  await interests.getByRole('button', { name: 'Label 30', exact: true }).click()
  await page.getByRole('button', { name: 'Add interest', exact: true }).click()
  await expect(interests.getByRole('button', { name: 'Unsent label', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Cancel interests' }).click()
  await expect(interests.getByRole('button', { name: 'Label 30', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const table = page.getByRole('table', { name: 'Weekly availability', exact: true })
  await expect(table.getByRole('button')).toHaveCount(28)
  await table.getByRole('button', { name: 'Monday morning, not available', exact: true }).focus()
  await page.keyboard.press('Space')
  await expect(table.getByRole('button', { name: 'Monday morning, available', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Cancel availability' }).click()
  await expect(table.getByRole('button', { name: 'Monday morning, not available', exact: true })).toHaveAttribute('aria-pressed', 'false')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
  expect(fixture.calls.some(call => call.method !== 'GET' || /\/(queue|result)$/.test(call.path))).toBe(false)
  expect(fixture.external).toEqual([])
})

test('inline interests retain multiline labels and reject duplicates without a write', async ({ page }) => {
  const fixture = await sharedProfileFixture(page, { interests: ['Board games\nstrategy', 'Coffee', 'Art'] })
  await page.goto('/profile')
  const interests = page.getByRole('group', { name: 'Usual interests' })
  await expect(interests.getByRole('button', { name: /Board games\s+strategy/ })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '+ Add an interest', exact: true }).click()
  await page.getByLabel('Your own interest').fill('Coffee')
  await page.getByRole('button', { name: 'Add interest', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('That interest is already selected.')
  expect(fixture.calls.some(call => call.method !== 'GET')).toBe(false)
  expect(fixture.external).toEqual([])
})
