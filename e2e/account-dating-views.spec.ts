  await expect(region.getByRole('button')).toHaveCount(6)
  await expect(region.locator('[data-dating-card]')).toHaveCount(3)
  await expect(action.locator('svg')).toHaveAttribute('data-icon', 'heart')
  await expect(region.getByRole('button', { name: 'Skip recommendation', exact: true }).locator('svg')).toHaveAttribute('data-icon', 'x')
  const photos = region.locator('img.dating-portrait')
  await expect(photos).toHaveCount(3)
  await photos.evaluateAll(images => Promise.all(images.map(image => (image as HTMLImageElement).decode())))
  await expect(region.locator('[data-front]')).toHaveAttribute('data-presentation', 'photo')
  await expect(region.locator('[data-front] img')).toHaveAttribute('alt', '')
  await expect(region.locator('[data-front]')).toHaveAttribute('data-design', 'reference')
  await expect(region.locator('[data-front] img')).toHaveCSS('object-fit', width >= 1000 ? 'fill' : 'cover')
  await expect(region.getByRole('link')).toHaveCount(2)
  await expect(region.getByRole('img', { name: 'Photo 1 of 1', exact: true })).toHaveCount(1)
  await expect(region.locator('.dating-overlay-header .match-view-segments')).toHaveCount(1)
  await expect(region.locator('[data-front] .dating-eyebrow')).toHaveText('Prototype profile')
  const mobile = width <= 700, short = mobile && page.viewportSize()!.height <= 740
