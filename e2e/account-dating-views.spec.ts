  await expect(region.getByRole('button', { name: 'Undo local decision', exact: true })).toHaveCSS('width', `${mobile ? 44 : 48}px`)
  await expect(page.locator('.pt-main')).toHaveCSS('opacity', '1')
  const metrics = await region.evaluate(element => {
    const card = element.querySelector('[data-front]')!, cardBox = card.getBoundingClientRect()
    const controls = [...element.querySelectorAll('.dating-overlay-header a, .dating-filter, .dating-decisions button, [data-front] .dating-info')]
    const boxes = controls.map(control => control.getBoundingClientRect())
    const name = card.querySelector('.dating-name')!, age = card.querySelector('.dating-age')!, info = card.querySelector('.dating-info')!
    const nameBox = name.getBoundingClientRect(), infoBox = info.getBoundingClientRect()
    const photo = card.querySelector('img') as HTMLImageElement
    return { center: cardBox.x + cardBox.width / 2, cardLeft: cardBox.left, cardWidth: cardBox.width, cardHeight: cardBox.height, cardBottom: cardBox.bottom, targets: boxes.map(box => ({ width: box.width, height: box.height })), inside: boxes.every(box => box.left >= cardBox.left && box.right <= cardBox.right && box.top >= cardBox.top && box.bottom <= cardBox.bottom), infoCircle: Math.abs(infoBox.width - infoBox.height) < .1 && Math.abs(infoBox.height - 44) < .1, centerline: Math.abs(nameBox.y + nameBox.height / 2 - (infoBox.y + infoBox.height / 2)), serif: getComputedStyle(name).fontFamily.includes('Georgia'), sansAge: getComputedStyle(age).fontFamily.includes('Arial'), photoLoaded: photo.complete && photo.naturalWidth > 0 && photo.getAttribute('src')?.startsWith('/prototype/dating/'), gradient: getComputedStyle(card.querySelector('.dating-photo-scrim')!).backgroundImage.includes('linear-gradient'), bubbles: card.querySelectorAll('li').length }
  })
  expect(Math.abs(metrics.center - width / 2)).toBeLessThanOrEqual(1)
  for (const target of metrics.targets) { expect(target.width).toBeGreaterThanOrEqual(44); expect(target.height).toBeGreaterThanOrEqual(44) }
  expect(metrics.inside).toBe(true); expect(metrics.infoCircle).toBe(true); expect(metrics.centerline).toBeLessThanOrEqual(1)
  expect(metrics.serif).toBe(true); expect(metrics.sansAge).toBe(true); expect(metrics.photoLoaded).toBe(true); expect(metrics.gradient).toBe(true)
