import { expect, test } from '@playwright/test'
import { sharedProfileFixture } from './shared-profile-fixture'

for (const width of [320, 390, 1440]) {
  test(`Profile canonical facts, visibility and picture preview at ${width}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: width === 1440 ? 900 : 844 })
    const fixture = await sharedProfileFixture(page)
    await page.goto('/profile')
    await page.getByRole('button', { name: 'Edit profile', exact: true }).click()
    const mainEditor = page.getByRole('dialog', { name: 'Edit your profile', exact: true })
    await expect(mainEditor.getByLabel('Birthdate', { exact: true })).toHaveAttribute('max', /\d{4}-\d{2}-\d{2}/)
    await page.screenshot({ path: testInfo.outputPath('profile-core-editor.png') })
    await mainEditor.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Edit profile', exact: true })).toBeFocused()
    await page.getByRole('button', { name: 'Edit details', exact: true }).click()
    const editor = page.getByRole('dialog', { name: 'Education, work & languages' })
    await editor.getByLabel('Education', { exact: true }).fill('Stony Brook University')
    await editor.getByLabel('Occupation', { exact: true }).fill('Research assistant')
    await editor.getByLabel('Languages', { exact: true }).fill('English')
    await editor.getByRole('button', { name: 'Add language', exact: true }).click()
    await editor.getByLabel('Languages', { exact: true }).fill('english')
    await editor.getByRole('button', { name: 'Add language', exact: true }).click()
    await expect(editor.getByRole('alert')).toContainText('once')
    await editor.getByLabel('Languages', { exact: true }).fill('')
    await editor.getByLabel('Show my occupation on my profile').uncheck()
    await editor.getByLabel('Show my education on my profile').check()
    await editor.getByLabel('Show my languages on my profile').check()
    await page.screenshot({ path: testInfo.outputPath('profile-facts-editor.png') })
    await editor.getByRole('button', { name: 'Save details', exact: true }).click()
    await expect(editor).not.toBeVisible()
    await page.getByRole('button', { name: 'Preview public profile' }).click()
    const viewer = page.getByRole('dialog', { name: 'Public profile preview' })
    await expect(viewer).toContainText('Stony Brook University')
    await expect(viewer).toContainText('English')
    await expect(viewer).not.toContainText('Research assistant')
    await expect(viewer).not.toContainText('2000-01-01')
    await page.screenshot({ path: testInfo.outputPath('profile-public-preview.png') })
    await viewer.getByRole('button', { name: 'Close dialog' }).click()
    await page.getByRole('button', { name: 'Profile picture', exact: true }).click()
    const picture = page.getByRole('dialog', { name: 'Your profile picture' })
    await picture.getByLabel('Choose a picture').setInputFiles({ name: 'invalid.svg', mimeType: 'image/svg+xml', buffer: Buffer.from('<svg/>') })
    await expect(picture.getByRole('alert')).toContainText('JPG, PNG or WebP')
    await picture.getByLabel('Choose a picture').setInputFiles('public/prototype/account/profile-cafe.jpg')
    await expect(picture.getByRole('img', { name: 'Selected profile picture preview' })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('profile-picture.png') })
    await picture.getByRole('button', { name: 'Apply picture preview' }).click()
    await expect(page.locator('.account-portrait')).toHaveAttribute('src', /^data:image\/jpeg/)
    await page.getByRole('button', { name: 'Edit details', exact: true }).click()
    await editor.getByLabel('Education', { exact: true }).fill('Discard me')
    await page.keyboard.press('Escape')
    await expect(page.getByRole('region', { name: 'Profile details and visibility' })).not.toContainText('Discard me')
    await page.getByRole('region', { name: 'Profile details and visibility' }).scrollIntoViewIfNeeded()
    await page.screenshot({ path: testInfo.outputPath('profile-details.png') })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    expect(fixture.calls.filter(call => call.method !== 'GET')).toEqual([{ path: '/api/matchmaking/profile-details', method: 'PUT', body: { expectedRevision: 0, facts: { education: 'Stony Brook University', occupation: 'Research assistant', languages: ['English'], visibility: { education: true, occupation: false, languages: true } } } }])
    expect(fixture.external).toEqual([])
    await page.reload()
    await expect(page.getByRole('region', { name: 'Profile details and visibility' })).toContainText('Stony Brook University')
  })
}

