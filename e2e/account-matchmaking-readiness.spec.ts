test('new dialogs fit a short mobile viewport and keep actions reachable', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 420 })
  const fixture = await sharedProfileFixture(page)
  await page.goto('/profile')
  for (const [opener, title, action] of [
    ['Edit details', 'Education, work & languages', 'Save details'],
    ['Profile picture', 'Your profile picture', 'Apply picture preview'],
    ['Preview public profile', 'Public profile preview', 'Close dialog'],
  ]) {
    await page.getByRole('button', { name: opener, exact: true }).click()
    const dialog = page.getByRole('dialog', { name: title, exact: true })
    const bounds = (await dialog.boundingBox())!
    expect(bounds.y).toBeGreaterThanOrEqual(0); expect(bounds.y + bounds.height).toBeLessThanOrEqual(420)
    await dialog.getByRole('button', { name: action, exact: true }).scrollIntoViewIfNeeded()
    await expect(dialog.getByRole('button', { name: action, exact: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath(`${opener.replaceAll(' ', '-')}-short.png`) })
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: opener, exact: true })).toBeFocused()
  }
  await page.goto('/matchmaking')
  await page.getByRole('button', { name: 'Preferences', exact: true }).click()
  const sheet = page.getByRole('dialog', { name: 'Your kind of connection.' })
  await sheet.getByRole('button', { name: 'Save Friends filters' }).scrollIntoViewIfNeeded()
  await expect(sheet.getByRole('button', { name: 'Save Friends filters' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('friends-short.png') })
  await page.keyboard.press('Escape')
  await page.getByRole('link', { name: 'Dating', exact: true }).click()
  await page.getByRole('button', { name: 'Prototype preferences', exact: true }).click()
  await sheet.getByRole('button', { name: 'Save disabled Dating draft', exact: true }).scrollIntoViewIfNeeded()
  await expect(sheet.getByRole('button', { name: 'Save disabled Dating draft', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('dating-short.png') })
  expect(await sheet.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  expect(fixture.calls.filter(call => call.method !== 'GET')).toEqual([])
  expect(fixture.external).toEqual([])
})

