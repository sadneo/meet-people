import { expect, test } from '@playwright/test'
import { sharedProfileFixture } from './shared-profile-fixture'

for (const width of [320, 390, 1440]) {
  test(`shared Profile and Matchmaking at ${width}: full contract, separate identity writes, authoritative route readback`, async ({ page }) => {
    const fixture = await sharedProfileFixture(page)
    await page.setViewportSize({ width, height: width === 320 ? 568 : width === 390 ? 844 : 900 })
    await page.goto('/profile')
    const edit = page.getByRole('button', { name: 'Edit profile', exact: true })
    await expect(page.getByRole('heading', { name: 'Canonical Sam', exact: true })).toBeVisible()
    const storage = await page.evaluate(() => [JSON.stringify(localStorage), JSON.stringify(sessionStorage)])
    await edit.click()
    const editor = page.getByRole('dialog', { name: 'Edit your profile', exact: true })
    const save = editor.getByRole('button', { name: 'Save shared preferences', exact: true })
    await expect(save).toBeEnabled()
    await expect(editor.getByRole('button', { name: 'Hiking', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(editor.getByRole('button', { name: 'Tuesday morning, custom times; edit exact windows', exact: true })).toBeDisabled()
    await editor.getByLabel('Display name', { exact: true }).fill('Unsubmitted identity')
    await editor.getByLabel('Bio', { exact: true }).fill('Unsubmitted bio')
    await editor.getByLabel('Add a matching interest').fill('Climbing')
    await editor.getByRole('button', { name: 'Add interest', exact: true }).click()
    await editor.getByRole('button', { name: 'Coffee', exact: true }).click()
    await editor.getByRole('button', { name: 'Monday afternoon, not available', exact: true }).focus()
    await page.keyboard.press('Space')
    await editor.getByLabel('City or campus area').fill('North campus')
    await editor.getByLabel('Birthdate', { exact: true }).fill('2001-02-03')
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    expect(await editor.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    const sizes = await editor.locator('button, input, textarea').evaluateAll(elements => elements.map(element => element.getBoundingClientRect()).filter(box => box.width && box.height).map(box => ({ width: box.width, height: box.height })))
    for (const size of sizes) { expect(size.width).toBeGreaterThanOrEqual(44); expect(size.height).toBeGreaterThanOrEqual(44) }
    console.log(`Shared Profile targets ${width}: minimum ${Math.min(...sizes.map(size => size.width))}×${Math.min(...sizes.map(size => size.height))}`)
    await editor.getByRole('group', { name: 'Interests', exact: true }).evaluate(element => element.scrollIntoView({ block: 'start' }))
    await page.screenshot({ path: `worktree/active-settings-optin/profile-picker-${width}.png`, animations: 'disabled' })
    await save.scrollIntoViewIfNeeded(); await expect(save).toBeInViewport()
    await page.screenshot({ path: `worktree/shared-profile/profile-editor-${width}.png`, animations: 'disabled' })
    await save.click(); await expect(editor).toHaveCount(0)
    const preferenceWrites = fixture.calls.filter(call => call.path.endsWith('/profile') && call.method === 'PUT')
    expect(preferenceWrites).toHaveLength(1)
    expect(preferenceWrites[0].body).toMatchObject({ display_name: 'Canonical Sam', bio: 'Canonical bio', location_city: 'North campus', birthdate: '2001-02-03', interests: ['Music', 'Books', 'Art', 'Games', 'Hiking', 'Climbing'] })
    expect(fixture.profile()!.availability).toEqual([{ dow: 2, start_time: '09:15:00', end_time: '11:45:00' }, { dow: 0, start_time: '21:00:00', end_time: '24:00:00' }, { dow: 1, start_time: '12:00:00', end_time: '17:00:00' }])
    expect(fixture.calls.at(-1)).toMatchObject({ path: '/api/matchmaking/profile', method: 'GET' })
    expect(fixture.calls.filter(call => call.path.endsWith('/account-profile') && call.method === 'PUT')).toEqual([])
    await page.screenshot({ path: `worktree/shared-profile/profile-${width}.png`, fullPage: true, animations: 'disabled' })
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Canonical Sam', exact: true })).toBeVisible()
    await edit.click(); await expect(save).toBeEnabled()
    await expect(editor.getByLabel('City or campus area')).toHaveValue('North campus')
    await expect(editor.getByLabel('Birthdate', { exact: true })).toHaveValue('2001-02-03')
    for (const label of ['Music', 'Books', 'Art', 'Games', 'Hiking', 'Climbing']) await expect(editor.getByRole('button', { name: label, exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(editor.getByRole('button', { name: 'Coffee', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await editor.getByRole('group', { name: 'Interests', exact: true }).evaluate(element => element.scrollIntoView({ block: 'start' }))
    await page.screenshot({ path: `worktree/interest-selection-review/profile-selected-${width}.png`, animations: 'disabled' })
    await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.getByRole('link', { name: 'Matchmaking', exact: true }).first().click()
    const summary = page.getByRole('region', { name: 'What brings you together', exact: true })
    await expect(summary).toContainText('North campus'); await expect(summary).toContainText('Climbing')
    await page.getByRole('button', { name: 'Preferences', exact: true }).click()
    const preferences = page.getByRole('dialog', { name: 'Your preferences', exact: true })
    await expect(preferences.getByRole('button', { name: 'Save preferences', exact: true })).toBeEnabled()
    for (const label of ['Music', 'Books', 'Art', 'Games', 'Hiking', 'Climbing']) await expect(preferences.getByRole('button', { name: label, exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(preferences.getByRole('button', { name: 'Coffee', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await preferences.getByRole('group', { name: 'Interests', exact: true }).evaluate(element => element.scrollIntoView({ block: 'start' }))
    await page.screenshot({ path: `worktree/interest-selection-review/matching-selected-${width}.png`, animations: 'disabled' })
    await expect(preferences.getByLabel('Display name', { exact: true })).toHaveCount(0)
    await expect(preferences.getByLabel('Bio', { exact: true })).toHaveCount(0)
    await expect(preferences.getByLabel('City or campus area')).toHaveCount(0)
    await expect(preferences.getByLabel('Birthdate (optional)')).toHaveCount(0)
    await preferences.getByRole('button', { name: 'Music', exact: true }).click()
    await preferences.getByLabel('Add a matching interest').fill('Live music')
    await preferences.getByRole('button', { name: 'Add interest', exact: true }).click()
    await preferences.getByLabel('Start 1', { exact: true }).fill('09:30:00')
    await preferences.getByRole('button', { name: 'Save preferences', exact: true }).click()
    await expect(preferences).toHaveCount(0)
    await page.reload()
    await page.getByRole('button', { name: 'Preferences', exact: true }).click()
    await expect(preferences.getByRole('button', { name: 'Save preferences', exact: true })).toBeEnabled()
    await expect(preferences.getByRole('button', { name: 'Live music', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(preferences.getByRole('button', { name: 'Music', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await preferences.getByRole('button', { name: 'Cancel', exact: true }).click()
    if (width > 800) await page.getByRole('button', { name: 'Account menu', exact: true }).click()
    await page.getByRole('link', { name: 'Profile', exact: true }).first().click()
    await edit.click(); await expect(save).toBeEnabled()
    await expect(editor.getByLabel('City or campus area')).toHaveValue('North campus')
    await expect(editor.getByLabel('Birthdate', { exact: true })).toHaveValue('2001-02-03')
    await expect(editor.getByRole('button', { name: 'Live music', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(editor.getByRole('button', { name: 'Music', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.reload(); await edit.click(); await expect(save).toBeEnabled()
    await expect(editor.getByRole('button', { name: 'Live music', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(editor.getByRole('button', { name: 'Music', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await editor.getByLabel('Display name', { exact: true }).fill('Updated name')
    await editor.getByLabel('Bio', { exact: true }).fill('Updated bio')
    await editor.getByRole('button', { name: 'Save identity', exact: true }).click()
    await expect(editor).toHaveCount(0)
    expect(fixture.calls.filter(call => call.path.endsWith('/profile') && call.method === 'PUT')).toHaveLength(2)
    expect(fixture.calls.filter(call => call.path.endsWith('/account-profile') && call.method === 'PUT')).toEqual([{ path: '/api/matchmaking/account-profile', method: 'PUT', body: { username: 'canonical-sam', display_name: 'Updated name', bio: 'Updated bio', avatar_url: null } }])
    await page.getByRole('link', { name: 'Matchmaking', exact: true }).first().click()
    await expect(summary).toContainText('Updated name'); await expect(summary).toContainText('Updated bio')
    await page.screenshot({ path: `worktree/shared-profile/matchmaking-${width}.png`, fullPage: true, animations: 'disabled' })
    expect(fixture.calls.some(call => /\/(queue|result)$/.test(call.path))).toBe(false)
    expect(await page.evaluate(() => [JSON.stringify(localStorage), JSON.stringify(sessionStorage)])).toEqual(storage)
    expect(fixture.external).toEqual([])
  })
}

for (const identity of ['missing', 'unavailable'] as const) {
  test(`app blocks shared Profile access until canonical identity is ${identity === 'missing' ? 'completed' : 'available'}`, async ({ page }) => {
    const fixture = await sharedProfileFixture(page, { identity })
    await page.goto('/profile')
    await expect(page.getByRole('heading', { name: identity === 'missing' ? 'Complete onboarding' : 'Profile unavailable', exact: true })).toBeVisible()
    await expect(page.locator('.pt-app')).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Save shared preferences', exact: true })).toHaveCount(0)
    if (identity === 'missing') await expect(page.getByLabel('Username', { exact: true })).toHaveValue('')
    else await expect(page.getByRole('form', { name: 'Profile identity', exact: true })).toHaveCount(0)
    expect(fixture.calls.length).toBeGreaterThan(0)
    expect(fixture.calls.every(call => call.method === 'GET' && /\/(account-profile|profile)$/.test(call.path))).toBe(true)
    expect(fixture.calls.some(call => call.method !== 'GET' || /\/(queue|result)$/.test(call.path))).toBe(false)
    expect(fixture.external).toEqual([])
  })
}
test('an absent shared profile requires real onboarding before Profile, without automatic writes', async ({ page }) => {
  const fixture = await sharedProfileFixture(page, { missingProfile: true })
  await page.goto('/profile/account')
  await expect(page.getByRole('heading', { name: 'Complete onboarding', exact: true })).toBeVisible()
  const editor = page.locator('.pt-access-card')
  await expect(editor.getByRole('button', { name: 'Finish onboarding', exact: true })).toBeEnabled()
  await expect(editor.getByLabel('City or campus area')).toHaveValue('')
  await expect(editor.getByRole('button', { name: 'Coffee', exact: true })).toHaveAttribute('aria-pressed', 'false')
  expect(fixture.calls.some(call => call.method !== 'GET')).toBe(false)
})
