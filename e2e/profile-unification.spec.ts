import { expect, test } from '@playwright/test'
import { sharedProfileFixture } from './shared-profile-fixture'

for (const width of [320, 390, 1440]) {
  test(`shared Profile and Matchmaking at ${width}: explicit facts/inline saves, canonical identity and reload`, async ({ page }) => {
    const fixture = await sharedProfileFixture(page)
    await page.setViewportSize({ width, height: width === 320 ? 568 : width === 390 ? 844 : 900 })
    await page.goto('/profile')
    const edit = page.getByRole('button', { name: 'Edit profile', exact: true })
    const editor = page.getByRole('dialog', { name: 'Edit your profile', exact: true })
    const usual = page.getByRole('group', { name: 'Usual interests' })
    await expect(page.getByRole('heading', { name: 'Canonical Sam', exact: true })).toBeVisible()
    const storage = await page.evaluate(() => [JSON.stringify(localStorage), JSON.stringify(sessionStorage)])
    const exactBefore = structuredClone(fixture.profile()!.availability)
    await edit.click()
    await expect(editor.getByLabel('Display name', { exact: true })).toHaveValue('Canonical Sam')
    await expect(editor.getByRole('table')).toHaveCount(0)
    await editor.getByLabel('City or campus area').fill('North campus')
    await editor.getByLabel('Birthdate', { exact: true }).fill('2001-02-03')
    await editor.getByRole('button', { name: 'Save profile', exact: true }).click()
    await expect(editor).toHaveCount(0)
    expect(fixture.profile()!.availability).toEqual(exactBefore)
    expect(fixture.calls.filter(call => call.path.endsWith('/account-profile') && call.method === 'PUT')).toEqual([])
    await page.getByRole('button', { name: '+ Add an interest', exact: true }).click()
    await page.getByLabel('Your own interest').fill('Climbing')
    await page.getByRole('button', { name: 'Add interest', exact: true }).click()
    await usual.getByRole('button', { name: 'Coffee', exact: true }).click()
    await page.getByRole('button', { name: 'Save usual interests' }).click()
    await expect(page.getByRole('button', { name: 'Save usual interests' })).toHaveCount(0)
    await page.getByRole('button', { name: 'Monday afternoon, not available', exact: true }).click()
    await page.getByRole('button', { name: 'Save usual availability' }).click()
    await expect(page.getByRole('button', { name: 'Save usual availability' })).toHaveCount(0)
    expect(fixture.profile()).toMatchObject({ display_name: 'Canonical Sam', bio: 'Canonical bio', location_city: 'North campus', birthdate: '2001-02-03', interests: ['Music', 'Books', 'Art', 'Games', 'Hiking', 'Climbing'] })
    expect(fixture.profile()!.availability).toEqual([...exactBefore, { dow: 1, start_time: '12:00:00', end_time: '17:00:00' }])
    await page.reload()
    await expect(usual.getByRole('button', { name: 'Climbing', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await edit.click()
    await expect(editor.getByLabel('City or campus area')).toHaveValue('North campus')
    await expect(editor.getByLabel('Birthdate', { exact: true })).toHaveValue('2001-02-03')
    await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
    await page.getByRole('link', { name: 'Matchmaking', exact: true }).first().click()
    await page.getByRole('button', { name: 'Preferences', exact: true }).click()
    const preferences = page.getByRole('dialog', { name: 'Your preferences', exact: true })
    await expect(preferences.getByRole('button', { name: 'Save preferences', exact: true })).toBeEnabled()
    for (const label of ['Music', 'Books', 'Art', 'Games', 'Hiking', 'Climbing']) await expect(preferences.getByRole('button', { name: label, exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(preferences.getByRole('button', { name: 'Coffee', exact: true })).toHaveAttribute('aria-pressed', 'false')
    for (const label of ['Display name', 'Bio', 'City or campus area']) await expect(preferences.getByLabel(label, { exact: true })).toHaveCount(0)
    await preferences.getByRole('button', { name: 'Music', exact: true }).click()
    await preferences.getByLabel('Add a matching interest').fill('Live music')
    await preferences.getByRole('button', { name: 'Add interest', exact: true }).click()
    await preferences.getByLabel('Start 1', { exact: true }).fill('09:30:00')
    await preferences.getByRole('button', { name: 'Save preferences', exact: true }).click()
    await expect(preferences).toHaveCount(0)
    await page.reload()
    await page.getByRole('button', { name: 'Preferences', exact: true }).click()
    await expect(preferences.getByRole('button', { name: 'Live music', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await preferences.getByRole('button', { name: 'Cancel', exact: true }).click()
    if (width > 800) await page.getByRole('button', { name: 'Account menu', exact: true }).click()
    await page.getByRole('link', { name: 'Profile', exact: true }).first().click()
    await expect(usual.getByRole('button', { name: 'Live music', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(usual.getByRole('button', { name: 'Music', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await edit.click()
    await expect(editor.getByLabel('City or campus area')).toHaveValue('North campus')
    await editor.getByLabel('Display name', { exact: true }).fill('Updated name')
    await editor.getByLabel('Bio', { exact: true }).fill('Updated bio')
    await editor.getByRole('button', { name: 'Save profile', exact: true }).click()
    await expect(editor).toHaveCount(0)
    expect(fixture.calls.filter(call => call.path.endsWith('/profile') && call.method === 'PUT')).toHaveLength(4)
    expect(fixture.calls.filter(call => call.path.endsWith('/account-profile') && call.method === 'PUT')).toEqual([{ path: '/api/matchmaking/account-profile', method: 'PUT', body: { username: 'canonical-sam', display_name: 'Updated name', bio: 'Updated bio', avatar_url: null } }])
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Updated name', exact: true })).toBeVisible()
    expect(fixture.calls.some(call => /\/(queue|result)$/.test(call.path))).toBe(false)
    expect(await page.evaluate(() => [JSON.stringify(localStorage), JSON.stringify(sessionStorage)])).toEqual(storage)
    expect(fixture.external).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
  })
}

for (const identity of ['missing', 'unavailable'] as const) {
  test(`app blocks shared Profile access until canonical identity is ${identity === 'missing' ? 'completed' : 'available'}`, async ({ page }) => {
    const fixture = await sharedProfileFixture(page, { identity })
    await page.goto('/profile')
    await expect(page.getByRole('heading', { name: identity === 'missing' ? 'Complete onboarding' : 'Profile unavailable', exact: true })).toBeVisible()
    await expect(page.locator('.pt-app')).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Save shared preferences', exact: true })).toHaveCount(0)
    if (identity === 'missing') await expect(page.getByLabel('Username', { exact: true })).toHaveValue('')
    else await expect(page.getByRole('form', { name: 'Profile identity', exact: true })).toHaveCount(0)
    expect(fixture.calls.length).toBeGreaterThan(0)
    expect(fixture.calls.every(call => call.method === 'GET' && call.path === '/api/matchmaking/account')).toBe(true)
    expect(fixture.calls.some(call => call.method !== 'GET' || /\/(queue|result)$/.test(call.path))).toBe(false)
    expect(fixture.external).toEqual([])
  })
}
test('an absent shared profile requires real onboarding before Profile, without automatic writes', async ({ page }) => {
  const fixture = await sharedProfileFixture(page, { missingProfile: true })
  await page.goto('/profile/account')
  await expect(page.getByRole('heading', { name: 'Complete onboarding', exact: true })).toBeVisible()
  const editor = page.locator('.pt-access-card')
  await expect(editor.getByRole('button', { name: 'Save interests and continue', exact: true })).toBeEnabled()
  await expect(editor.getByLabel('City or campus area')).toHaveCount(0)
  await expect(editor.getByRole('button', { name: 'Coffee', exact: true })).toHaveAttribute('aria-pressed', 'false')
  expect(fixture.calls.some(call => call.method !== 'GET')).toBe(false)
})
